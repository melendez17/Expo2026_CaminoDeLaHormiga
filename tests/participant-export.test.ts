import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ExcelJS from 'exceljs';
import { buildParticipantWorkbook, participantExcel } from '../src/lib/participant-export';
import { localDataSchema, freshProgress, completeLocal, generateExtras, storageKey, type LocalChallenge, type LocalProgress } from '../src/lib/local-game';
const keys=['users','projects','challenges','agenda','settings'];
const data=localDataSchema.parse(Object.fromEntries(keys.map(key=>[key,JSON.parse(readFileSync(new URL(`../public/data/${key}.json`,import.meta.url),'utf8'))])));
data.users[0].token='000A'; data.users[0].nationalId='0000123'; data.users[0].email='';
const at='2026-10-22T16:00:00.000Z';
const answers=(c:LocalChallenge):Record<string,string>=>c.kind==='freeform'?{projectName:'=1+1',level:'Quinto',description:'Línea uno\nLínea dos sobre tecnología.'}:c.kind==='saint'?{saint:c.answer!}:{code:c.code!,...Object.fromEntries((c.questions??[]).map(q=>[q.id,String(q.correctIndex)]))};
let ana:LocalProgress={...freshProgress(data,'ana'),startedAt:at};
for(const c of data.challenges.filter(c=>c.isBase)) ana=completeLocal(data,ana,c.id,answers(c));
ana=generateExtras(data,ana,()=>0);
const extra=data.challenges.find(c=>c.id===ana.extraIds[0])!;
ana=completeLocal(data,ana,extra.id,answers(extra));
ana={...ana,completed:ana.completed.map(c=>({...c,at})),survey:{expectations:'Conocer proyectos\ny aprender.',interest:'Tecnología',satisfaction:5}};
let sofia:LocalProgress={...freshProgress(data,'sofia'),startedAt:at};
sofia=completeLocal(data,sofia,data.challenges.find(c=>c.isBase)!.id,answers(data.challenges.find(c=>c.isBase)!));
const values=new Map([
 [storageKey(data,'ana'),JSON.stringify(ana)],
 [storageKey(data,'sofia'),JSON.stringify(sofia)],
 [storageKey(data,'diego'),JSON.stringify({...freshProgress(data,'diego'),startedAt:at})]
]);
const storage={getItem:(key:string)=>values.get(key)??null};
test('Excel contains every participant, type and final state, including inactive and partially completed users',()=>{
 const workbook=buildParticipantWorkbook(data,storage), sheet=workbook.getWorksheet('Usuarios')!;
 assert.deepEqual(workbook.worksheets.map(s=>s.name),['Usuarios','Retos base','Retos extra','Encuestas']);
 assert.equal(sheet.rowCount,5);
 assert.deepEqual([2,3,4,5].map(r=>sheet.getCell(r,6).value),['Completado','Sin activar','En proceso','Activado sin retos']);
 assert.equal(sheet.getCell('B2').value,'Postulante (nuevo ingreso)');
 assert.equal(sheet.getCell('B3').value,'Visitante');
 assert.equal(sheet.getCell('C2').value,'0000123');
 assert.equal(sheet.getCell('E2').value,'000A');
 assert.equal(sheet.getCell('H2').value,5);
 assert.equal(sheet.getCell('I2').value,0);
 assert.equal(sheet.getCell('H4').value,1);
 assert.ok(sheet.autoFilter);
 assert.match(String(sheet.getCell('K2').value),/10:00/);
});
test('questions export selected option text, literal multiline answers and explicit pending states',()=>{
 const workbook=buildParticipantWorkbook(data,storage), sheet=workbook.getWorksheet('Retos base')!;
 const quiz=data.challenges.find(c=>c.isBase&&c.kind==='quiz')!;
 const rows:ExcelJS.Row[]=[];sheet.eachRow((row,i)=>{if(i>1)rows.push(row);});
 const answered=rows.find(r=>r.getCell(1).value===data.users[0].name&&r.getCell(8).value===quiz.questions![0].prompt)!;
 assert.equal(answered.getCell(9).value,quiz.questions![0].options[quiz.questions![0].correctIndex]);
 const text=rows.find(r=>r.getCell(1).value===data.users[0].name&&r.getCell(8).value==='¿Qué descubriste?')!;
 assert.equal(text.getCell(9).value,'Línea uno\nLínea dos sobre tecnología.');
 const formula=rows.find(r=>r.getCell(9).value==='=1+1')!;
 assert.equal(formula.getCell(9).type,ExcelJS.ValueType.String);
 const pending=rows.filter(r=>r.getCell(1).value===data.users.find(u=>u.id==='carlos')!.name);
 assert.ok(pending.length>5);
 assert.ok(pending.every(r=>r.getCell(7).value==='Pendiente'&&r.getCell(9).value===''));
 const extras=workbook.getWorksheet('Retos extra')!;
 const extraRows:ExcelJS.Row[]=[];extras.eachRow((r,i)=>{if(i>1)extraRows.push(r);});
 assert.ok(extraRows.some(r=>r.getCell(7).value==='Completado'));
 assert.ok(extraRows.some(r=>r.getCell(7).value==='Pendiente'));
 assert.ok(extraRows.every(r=>r.getCell(1).value===data.users[0].name));
 assert.equal(workbook.getWorksheet('Encuestas')!.getCell('H2').value,'Conocer proyectos\ny aprender.');
});
test('generated bytes are an actual XLSX and preserve text IDs, tokens and formula-like answers on reopening',async()=>{
 const bytes=await participantExcel(data,storage);
 assert.deepEqual(Array.from(new Uint8Array(bytes).slice(0,2)),[0x50,0x4b]);
 const read=new ExcelJS.Workbook();await read.xlsx.load(bytes);
 assert.equal(read.getWorksheet('Usuarios')!.getCell('C2').value,'0000123');
 assert.equal(read.getWorksheet('Usuarios')!.getCell('E2').value,'000A');
 let found=false;read.getWorksheet('Retos base')!.eachRow(row=>{if(row.getCell(9).value==='=1+1'){found=true;assert.equal(row.getCell(9).type,ExcelJS.ValueType.String);}});
 assert.ok(found);
});
test('invalid saved progress blocks export instead of silently losing participant answers',()=>{
 assert.throws(()=>buildParticipantWorkbook(data,{getItem:key=>key===storageKey(data,'ana')?'not-json':null}),/Revisa el progreso guardado de: Ana/);
});
