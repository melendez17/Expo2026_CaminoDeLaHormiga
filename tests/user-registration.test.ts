import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createParticipant, generateUserToken, parseParticipantDetails } from '../src/lib/user-registration';
import { localDataSchema } from '../src/lib/local-game';
const keys = ['users', 'projects', 'challenges', 'agenda', 'settings'];
const data = localDataSchema.parse(Object.fromEntries(keys.map(key => [key, JSON.parse(readFileSync(new URL(`../public/data/${key}.json`, import.meta.url), 'utf8'))])));
test('hexadecimal tokens include A-F, preserve four characters and exclude occupied tokens', () => {
  assert.equal(generateUserToken([{token:'0000'},{token:'K8P2'}],()=>0),'0001');
  assert.equal(generateUserToken([],()=>10),'000A');
  assert.equal(generateUserToken([],()=>0xFFFF),'FFFF');
  const occupied=Array.from({length:0x10000},(_,i)=>({token:i.toString(16).toUpperCase().padStart(4,'0')}));
  assert.throws(()=>generateUserToken(occupied),/No quedan tokens/);
  assert.equal(generateUserToken(occupied.filter(u=>u.token!=='A7F2'),()=>0),'A7F2');
});
test('visitors need no identification and receive a unique hexadecimal token', () => {
  const first=createParticipant(data,{kind:'visitor',name:'  Persona Prueba  '});
  assert.equal(first.nationalId,undefined);
  assert.equal(first.name,'Persona Prueba');
  assert.equal(first.email,undefined);
  assert.match(first.token,/^[0-9A-F]{4}$/);
  assert.equal(first.role,'participant');
  const second=createParticipant({...data,users:[...data.users,first]},{kind:'visitor',nationalId:'unused',name:'Otra Persona'});
  assert.equal(second.nationalId,undefined);
  assert.notEqual(first.token,second.token);
});
test('applicant identification is required free text and preserves literal document text on create, edit and export', () => {
  const identification=' Pasaporte Ab-12 / 345 '.repeat(8);
  const applicant=createParticipant(data,{kind:'applicant',nationalId:identification,name:'Postulante',email:' persona@example.com '});
  assert.equal(applicant.nationalId,identification);
  assert.equal(applicant.email,'persona@example.com');
  const next={...data,users:[...data.users,applicant]};
  assert.equal(localDataSchema.parse(JSON.parse(JSON.stringify(next))).users.at(-1)!.nationalId,identification);
  assert.throws(()=>createParticipant(next,{kind:'applicant',nationalId:identification,name:'Duplicada'}),/esa identificación/);
  assert.throws(()=>createParticipant(data,{kind:'applicant',name:'Persona'}),/identificación/);
  assert.throws(()=>createParticipant(data,{kind:'applicant',nationalId:'   ',name:'Persona'}),/identificación/);
  assert.equal(parseParticipantDetails({kind:'applicant',nationalId:'AB-cd 123',name:'Editada'}).nationalId,'AB-cd 123');
  assert.equal(parseParticipantDetails({kind:'visitor',nationalId:'AB-cd 123',name:'Editada'}).nationalId,undefined);
  assert.throws(()=>createParticipant(data,{kind:'visitor',name:' '}));
  assert.throws(()=>createParticipant(data,{kind:'visitor',name:'Persona',email:'invalid'}));
});
